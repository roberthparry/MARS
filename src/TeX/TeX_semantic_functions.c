/* Reject non-members after the perfect hash selects one candidate. */
static const char *function_spelling(const char *text, size_t length, unsigned char use)
{
    if (!text)
        return NULL;
    uint32_t first = 1u, second = 104u;
    for (size_t i = 0u; i < length; ++i) {
        unsigned char c = (unsigned char)text[i];
        first = (first ^ c) * UINT32_C(16777619);
        second = (second ^ c) * UINT32_C(16777619);
    }
    int displacement = function_displacements[first % 156u];
    size_t slot = displacement < 0 ? (size_t)(-displacement - 1) : ((uint64_t)second + (unsigned)displacement) % 156u;
    const TeX_function_spelling_t *entry = &function_spellings[slot];
    return (function_uses[slot] & use) && strlen(entry->name) == length && !memcmp(entry->name, text, length)
        ? entry->notation : NULL;
}

/* Resolve an operation name without retaining it. */
const char *TeX_operation_name(const char *name)
{
    return name ? function_spelling(name, strlen(name), 1u) : NULL;
}

/* Resolve a length-delimited semantic name; embedded NULs do not match. */
const char *TeX_semantic_function(const string_t *name)
{
    return name ? function_spelling(string_c_str(name), string_byte_length(name), 2u) : NULL;
}

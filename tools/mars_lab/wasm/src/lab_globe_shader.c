/**
 * @file lab_globe_shader.c
 * @brief Native-owned GLSL for photographic globe compositing and geographic overlays.
 *
 * The browser enables the derivative extension when supported, compiles these
 * sources once per context and updates numeric uniforms. Source selection is
 * native; no JavaScript shader generation or binary-shader extension is required.
 */
#include <stdlib.h>
#include <string.h>

#include "lab_dom.h"
#include "lab_globe_shader.h"

static const char globe_vertex[] =
    "attribute vec2 position; varying vec2 screen; void main(){screen=position;gl_Position=vec4(position,0.,1.);}";
static const char globe_fragment[] =
    "\n"
    "precision highp float;\n"
    "varying vec2 screen;\n"
    "uniform sampler2D world, detail, mapWorld;\n"
    "uniform sampler2D photoPatch;\n"
    "uniform bool photoReady;\n"
    "uniform vec4 photoBounds;\n"
    "uniform sampler2D rivers;\n"
    "uniform sampler2D shoreMask;\n"
    "uniform sampler2D landPalette, waterPalette;\n"
    "uniform bool palettesReady;\n"
    "uniform int palettePass;\n"
    "uniform bool naturalShore;\n"
    "uniform bool naturalStyle;\n"
    "uniform float shoreBlend;\n"
    "uniform vec4 shoreTransform;\n"
    "uniform vec3 shoreOffset;\n"
    "uniform vec4 shoreBounds;\n"
    "uniform float photoPixels;\n"
    "uniform vec4 riverBounds;\n"
    "uniform bool riverReady;\n"
    "uniform bool mapMode;\n"
    "uniform bool vectorReady;\n"
    "uniform bool interactionPreview;\n"
    "uniform vec3 camera;\n"
    "uniform mat3 cameraToWorld;\n"
    "uniform vec4 bounds;\n"
    "uniform bool detailReady;\n"
    "uniform bool grid;\n"
    "uniform float viewport;\n"
    "const float rad=0.017453292519943295;\n"
    "// Driver inverse-trigonometric approximations can shift close-up geography by kilometres.\n"
    "// Reduce atan2 to |t|<=tan(pi/8), then use a bounded odd series in highp arithmetic.\n"
    "float geographicAngle(float y,float x){\n"
    "    vec2 a=abs(vec2(x,y));\n"
    "    float major=max(a.x,a.y);\n"
    "    if(major==0.) return 0.;\n"
    "    float t=min(a.x,a.y)/major;\n"
    "    t=t/(1.+sqrt(1.+t*t));\n"
    "    float s=t*t;\n"
    "    float series=-1./19.;\n"
    "    series=1./17.+s*series;\n"
    "    series=-1./15.+s*series;\n"
    "    series=1./13.+s*series;\n"
    "    series=-1./11.+s*series;\n"
    "    series=1./9.+s*series;\n"
    "    series=-1./7.+s*series;\n"
    "    series=1./5.+s*series;\n"
    "    series=-1./3.+s*series;\n"
    "    float angle=2.*t*(1.+s*series);\n"
    "    if(a.y>a.x) angle=1.5707963267948966-angle;\n"
    "    if(x<0.) angle=3.141592653589793-angle;\n"
    "    return y<0.?-angle:angle;\n"
    "}\n"
    "float iceCoverage(vec3 colour){\n"
    "    float low=min(colour.r,min(colour.g,colour.b));\n"
    "    float high=max(colour.r,max(colour.g,colour.b));\n"
    "    return smoothstep(.80,.95,low)*(1.-smoothstep(.08,.18,high-low));\n"
    "}\n"
    "float iceSample(vec2 uv){\n"
    "    return iceCoverage(texture2D(world,vec2(fract(uv.x),clamp(uv.y,0.,1.))).rgb);\n"
    "}\n"
    "float roundedIce(vec2 uv,vec3 globe){\n"
    "    // Illustrative reconstruction only: soften source-cell stairs, then retain a crisp contour.\n"
    "    // World-anchored undulation never changes with dragging, frame timing or request completion.\n"
    "    vec2 texel=vec2(1.,2.)/max(photoPixels,1.);\n"
    "    vec3 phase=globe*max(photoPixels,1.);\n"
    "    vec2 drift=vec2(sin(phase.x*.19+phase.z*.13),sin(phase.z*.17-phase.x*.11));\n"
    "    drift+=.45*vec2(sin(phase.z*.43-phase.x*.31),sin(phase.x*.41+phase.z*.29));\n"
    "    drift+=.2*vec2(sin(phase.x*.91+phase.z*.73),sin(phase.z*.83-phase.x*.67));\n"
    "    uv+=texel*drift;\n"
    "    // An oblique circular kernel avoids reinforcing the source image's square lattice.\n"
    "    vec2 a=texel*vec2(1.47821,.61229),b=texel*vec2(.61229,1.47821);\n"
    "    vec2 c=texel*vec2(-.61229,1.47821),d=texel*vec2(-1.47821,.61229);\n"
    "    // Avoid exact half-coverage plateaux when every tap falls inside a binary source cell.\n"
    "    float coverage=iceSample(uv)*4.25;\n"
    "    coverage+=iceSample(uv+a)+iceSample(uv-a)+iceSample(uv+b)+iceSample(uv-b);\n"
    "    coverage+=iceSample(uv+c)+iceSample(uv-c)+iceSample(uv+d)+iceSample(uv-d);\n"
    "    return coverage/12.25;\n"
    "}\n"
    "vec3 surfacePhoto(vec2 uv){\n"
    "    vec3 base=texture2D(world,uv).rgb;\n"
    "    if(!photoReady || palettePass!=0 || camera.z<=4.) return base;\n"
    "    float lon=uv.x*360.-180., lat=90.-uv.y*180.;\n"
    "    float centre=(photoBounds.x+photoBounds.z)*.5;\n"
    "    lon=centre+mod(lon-centre+180.,360.)-180.;\n"
    "    vec2 local=vec2((lon-photoBounds.x)/(photoBounds.z-photoBounds.x),\n"
    "                    (photoBounds.w-lat)/(photoBounds.w-photoBounds.y));\n"
    "    if(local.x<0. || local.x>1. || local.y<0. || local.y>1.) return base;\n"
    "    vec2 edge=min(local,1.-local);\n"
    "    float blend=smoothstep(0.,.04,min(edge.x,edge.y))*smoothstep(4.,8.,camera.z);\n"
    "    return mix(base,texture2D(photoPatch,local).rgb,blend);\n"
    "}\n"
    "vec3 mapColour(vec3 mask,vec2 location){\n"
    "    bool land=mask.g>mask.b || mask.r>.8;\n"
    "    // Preserve world-anchored photography at every scale. Only repair pixels whose\n"
    "    // photographic surface disagrees with the more detailed surveyed shoreline.\n"
    "    vec3 photo=surfacePhoto(vec2(fract((location.x+180.)/360.),(90.-location.y)/180.));\n"
    "    float blue=photo.b-max(photo.r,photo.g);\n"
    "    float low=min(photo.r,min(photo.g,photo.b)), high=max(photo.r,max(photo.g,photo.b));\n"
    "    float ice=smoothstep(.65,.75,low)*(1.-smoothstep(.15,.22,high-low));\n"
    "    float match=land?max(smoothstep(0.,.08,-blue),ice):smoothstep(0.,.08,blue);\n"
    "    if(match==1.) return photo;\n"
    "    if(palettesReady && palettePass==0) {\n"
    "        vec2 uv=vec2(fract((location.x+180.)/360.),clamp((90.-location.y)/180.,0.,1.));\n"
    "        vec3 palette=land?texture2D(landPalette,uv).rgb:texture2D(waterPalette,uv).rgb;\n"
    "        return mix(palette,photo,match);\n"
    "    }\n"
    "    // A moving local average retains photographic colour, not magnified raster detail.\n"
    "    // Reject opposite-surface samples so water cannot tint a crisp land boundary.\n"
    "    vec3 total=vec3(0.);\n"
    "    float weights=0.;\n"
    "    float available=0.;\n"
    "    for(int y=-2;y<=2;y++) for(int x=-2;x<=2;x++) {\n"
    "        vec2 offset=vec2(float(x),float(y));\n"
    "        vec2 sampleLocation=location+offset*.08;\n"
    "        vec2 sampleUV=vec2(fract((sampleLocation.x+180.)/360.),\n"
    "                           clamp((90.-sampleLocation.y)/180.,0.,1.));\n"
    "        vec3 sampleColour=texture2D(world,sampleUV).rgb;\n"
    "        float low=min(sampleColour.r,min(sampleColour.g,sampleColour.b));\n"
    "        float high=max(sampleColour.r,max(sampleColour.g,sampleColour.b));\n"
    "        float blue=sampleColour.b-max(sampleColour.r,sampleColour.g);\n"
    "        float ice=smoothstep(.65,.75,low)*(1.-smoothstep(.15,.22,high-low));\n"
    "        // Fade eligibility at colour thresholds: binary rejection creates visible contour patches.\n"
    "        // Opposite-surface samples still have zero weight; only land accepts neutral ice.\n"
    "        float match=land?max(smoothstep(0.,.08,-blue),ice):smoothstep(0.,.08,blue);\n"
    "        float weight=1./(1.+dot(offset,offset));\n"
    "        available+=weight;\n"
    "        total+=sampleColour*(weight*match);\n"
    "        weights+=weight*match;\n"
    "    }\n"
    "    // Missing photographic water samples must never fill a mapped channel with land colour.\n"
    "    // Fade to the matching surface fallback instead of jumping when the last sample disappears.\n"
    "    vec3 palette=mix(mask,total/max(weights,.000001),smoothstep(0.,1.,weights/available));\n"
    "    if(palettePass!=0) return palette;\n"
    "    return mix(palette,photo,match);\n"
    "}\n"
    "void main(){\n"
    "    if(palettePass!=0) {\n"
    "        vec3 mask=palettePass==1?vec3(70.,85.,34.)/255.:vec3(7.,20.,64.)/255.;\n"
    "        gl_FragColor=vec4(mapColour(mask,vec2(screen.x*180.,-screen.y*90.)),1.);return;\n"
    "    }\n"
    "    vec2 p=vec2(screen.x,-screen.y)*1.12/camera.z;\n"
    "    float r=dot(p,p); if(r>1.){gl_FragColor=vec4(0.);return;}\n"
    "    float z=sqrt(max(0.,1.-r));\n"
    "    vec3 globe=cameraToWorld*vec3(p.x,-p.y,z);\n"
    "    float lat=geographicAngle(globe.y,length(globe.xz))/rad;\n"
    "    float lon=geographicAngle(globe.x,globe.z)/rad;\n"
    "    lon=mod(lon+180.,360.)-180.;\n"
    "    vec4 colour=texture2D(world,vec2((lon+180.)/360.,(90.-lat)/180.));\n"
    "    vec3 referenceIce=colour.rgb;\n"
    "    colour.rgb=surfacePhoto(vec2((lon+180.)/360.,(90.-lat)/180.));\n"
    "    vec3 photographic=colour.rgb;\n"
    "    if(mapMode && !vectorReady) colour=texture2D(mapWorld,vec2((lon+180.)/360.,(90.-lat)/180.));\n"
    "    float centre=(bounds.x+bounds.z)*.5;\n"
    "    float unwrapped=centre+mod(lon-centre+180.,360.)-180.;\n"
    "    vec2 uv=vec2((unwrapped-bounds.x)/(bounds.z-bounds.x),(bounds.w-lat)/(bounds.w-bounds.y));\n"
    "    if(detailReady && camera.z>1.5 && uv.x>=0. && uv.x<=1. && uv.y>=0. && uv.y<=1.) {\n"
    "        vec4 coast=texture2D(detail,uv);\n"
    "        colour.rgb=mix(colour.rgb,coast.rgb,mapMode?1.:coast.a*smoothstep(2.,6.,camera.z));\n"
    "    }\n"
    "    if(mapMode && !vectorReady) {\n"
    "        if(interactionPreview && !naturalStyle) {\n"
    "            bool land=colour.g>colour.b || colour.r>.8;\n"
    "            float ice=smoothstep(55.,80.,abs(lat));\n"
    "            colour.rgb=land?mix(vec3(70.,85.,34.)/255.,vec3(243.,245.,242.)/255.,ice):vec3(7.,20.,64.)/255.;\n"
    "        } else colour.rgb=mapColour(colour.rgb,vec2(lon,lat));\n"
    "    }\n"
    "    if(naturalShore) {\n"
    "        // The GPU mask uses the same native projection as the visible SVG,\n"
    "        // with overscan. It is not the coarse geographical preview texture.\n"
    "        vec2 pixel=vec2(screen.x+1.,1.-screen.y)*viewport*.5-shoreOffset.xy;\n"
    "        float determinant=shoreTransform.x*shoreTransform.w-shoreTransform.y*shoreTransform.z;\n"
    "        vec2 oldPixel=vec2(shoreTransform.w*pixel.x-shoreTransform.z*pixel.y,\n"
    "                          -shoreTransform.y*pixel.x+shoreTransform.x*pixel.y)/determinant;\n"
    "        vec2 maskUV=(oldPixel/shoreOffset.z+.5)*.5;\n"
    "        float shoreLongitude=(shoreBounds.x+shoreBounds.z)*.5;\n"
    "        shoreLongitude+=mod(lon-shoreLongitude+180.,360.)-180.;\n"
    "        bool covered=lat>=shoreBounds.y && lat<=shoreBounds.w &&\n"
    "            (shoreBounds.z-shoreBounds.x>=359.999 ||\n"
    "             (shoreLongitude>=shoreBounds.x && shoreLongitude<=shoreBounds.z)) &&\n"
    "            maskUV.x>=0. && maskUV.x<=1. && maskUV.y>=0. && maskUV.y<=1.;\n"
    "        float land=texture2D(shoreMask,maskUV).r;\n"
    "        // Outside the retained patch keep the original photograph;\n"
    "        // corrected pixels fade back to it near the mask edge.\n"
    "        if(!covered) colour.rgb=photographic;\n"
    "        else if(land<=0.) colour.rgb=mapColour(vec3(7.,20.,64.)/255.,vec2(lon,lat));\n"
    "        else if(land>=1.) colour.rgb=mapColour(vec3(70.,85.,34.)/255.,vec2(lon,lat));\n"
    "        else colour.rgb=mix(mapColour(vec3(7.,20.,64.)/255.,vec2(lon,lat)),\n"
    "                            mapColour(vec3(70.,85.,34.)/255.,vec2(lon,lat)),land);\n"
    "        vec2 edge=min(maskUV,1.-maskUV);\n"
    "        float coverage=smoothstep(0.,.03,min(edge.x,edge.y));\n"
    "        colour.rgb=mix(photographic,colour.rgb,shoreBlend*coverage);\n"
    "    }\n"
    "    float light=.8+.2*max(0.,dot(vec3(p.x,-p.y,z),normalize(vec3(-.35,.45,1.))));\n"
    "    vec3 surface=mix(colour.rgb*light,vec3(.32,.60,.88),.18*pow(1.-z,4.));\n"
    "    if(interactionPreview) surface=colour.rgb;\n"
    "    vec4 overlay=vec4(0.);\n"
    "    if(riverReady && camera.z>=12.) {\n"
    "        float rc=(riverBounds.x+riverBounds.z)*.5;\n"
    "        float rl=rc+mod(lon-rc+180.,360.)-180.;\n"
    "        vec2 ru=vec2((rl-riverBounds.x)/(riverBounds.z-riverBounds.x),\n"
    "                     (riverBounds.w-lat)/(riverBounds.w-riverBounds.y));\n"
    "        if(ru.x>=0. && ru.x<=1. && ru.y>=0. && ru.y<=1.) {\n"
    "            vec4 river=texture2D(rivers,ru);\n"
    "            if(river.a>0.) {\n"
    "                vec3 water=mapColour(vec3(7.,20.,64.)/255.,vec2(lon,lat));\n"
    "                vec3 riverSurface=mix(water*light,vec3(.32,.60,.88),.18*pow(1.-z,4.));\n"
    "                surface=mix(surface,riverSurface,river.a);\n"
    "                overlay=vec4(riverSurface*river.a,river.a);\n"
    "            }\n"
    "        }\n"
    "    }\n"
    "    // Preserve historical polar ice pictured in the source composite in both hemispheres.\n"
    "    // This is imagery, not a land mask or a claim about present-day sea ice.\n"
    "    float iceSignal=iceCoverage(referenceIce);\n"
    "    float historicalIce=smoothstep(55.,65.,abs(lat))*iceSignal;\n"
    "    vec3 iceColour=referenceIce;\n"
    "    if(mapMode || vectorReady || naturalShore) {\n"
    "        // Reconstruct enlarged ice cells independently of the surveyed land mask.\n"
    "        float texelPixels=viewport*camera.z*6.28318530718/(2.24*max(photoPixels,1.));\n"
    "        float rounding=smoothstep(2.,5.,texelPixels);\n"
    "        // Reconstruct bright ice and its photographic fringe, not dark sea or vegetation.\n"
    "        // Avoid nine texture reads and procedural trigonometry across an ice-free close view.\n"
    "        float iceNeighbourhood=smoothstep(.55,.75,min(referenceIce.r,min(referenceIce.g,referenceIce.b)));\n"
    "        if(abs(lat)>55. && photoPixels>0. && rounding>0. && iceNeighbourhood>0.)\n"
    "            iceSignal=mix(iceSignal,roundedIce(vec2((lon+180.)/360.,(90.-lat)/180.),globe),rounding*iceNeighbourhood);\n"
    "        // Restrict edge antialiasing to approximately one screen pixel at every zoom.\n"
    "        #ifdef MARS_DERIVATIVES\n"
    "float edgeWidth=max(fwidth(iceSignal),.00001);\n"
    "#else\n"
    "float edgeWidth=.001;\n"
    "#endif\n"
    "        historicalIce=smoothstep(55.,65.,abs(lat))*smoothstep(.5-edgeWidth*.5,.5+edgeWidth*.5,iceSignal);\n"
    "        iceColour=vec3(243.,245.,242.)/255.;\n"
    "    }\n"
    "    surface=mix(surface,iceColour,historicalIce);\n"
    "    overlay=vec4(iceColour*historicalIce,historicalIce)+overlay*(1.-historicalIce);\n"
    "    if(grid) {\n"
    "        float step=camera.z<4.?15.:camera.z<12.?5.:camera.z<60.?1.:camera.z<240.?.25:camera.z<1200.?.05:.01;\n"
    "        float latitudeLine=abs(mod(lat+step*.5,step)-step*.5);\n"
    "        float longitudeLine=abs(mod(lon+step*.5,step)-step*.5);\n"
    "        float width=128./(viewport*camera.z);\n"
    "        // Keep every meridian, but prevent neighbouring strokes merging at the poles.\n"
    "        float latitudeWidth=min(width,step*.08);\n"
    "        float longitudeWidth=min(width/max(cos(lat*rad),.000001),step*.08);\n"
    "        float line=max(1.-smoothstep(latitudeWidth*.4,latitudeWidth*1.4,latitudeLine),\n"
    "                       1.-smoothstep(longitudeWidth*.4,longitudeWidth*1.4,longitudeLine));\n"
    "        // A middle-light ink contrasts with both ice and ocean. Never choose its colour\n"
    "        // from hidden photographic pixels underneath the independent SVG surface.\n"
    "        vec3 ink=vec3(.65,.72,.76);\n"
    "        float opacity=line*.65;\n"
    "        surface=mix(surface,ink,opacity);\n"
    "        overlay=vec4(ink*opacity,opacity)+overlay*(1.-opacity);\n"
    "    }\n"
    "    gl_FragColor=vectorReady && !naturalShore?overlay:vec4(surface,1.);\n"
    "}\n";

/* Supply a complete, immutable shader variant through the scoped browser bridge. */
void lab_globe_shader(unsigned fragment, unsigned derivatives)
{
    const char *prefix = fragment && derivatives
        ? "#extension GL_OES_standard_derivatives : enable\n#define MARS_DERIVATIVES\n" : "";
    const char *body = fragment ? globe_fragment : globe_vertex;
    size_t prefix_length = strlen(prefix), body_length = strlen(body);
    char *source = malloc(prefix_length + body_length);
    if (!source) { lab_dom_return(0); return; }
    memcpy(source, prefix, prefix_length);
    memcpy(source + prefix_length, body, body_length);
    lab_dom_return(lab_dom_utf8_string((const unsigned char *)source, prefix_length + body_length));
    free(source);
}

/**
 * @file lab_evaluation_dom.h
 * @brief Application API: projection of native solver renderings into the WASM worksheet.
 *
 * Chooses supplied TeX/SVG representations and diagnostic fallbacks for equation,
 * differential-equation and integrator cards. No mathematical text is parsed or
 * rewritten. C owns dataset/visibility policy; the browser supplies opaque native
 * records, DOM operations and asynchronous rendering when a representation is absent.
 *
 * Used by the freestanding browser modules and the versioned JavaScript host ABI.
 * This is not an installed MARS library interface; calls run synchronously on the browser thread.
 * Boolean arguments cross the WebAssembly i32 boundary as canonical 0 or 1, never scoped handles.
 */
#ifndef LAB_WASM_EVALUATION_DOM_H
#define LAB_WASM_EVALUATION_DOM_H

#include <stdbool.h>

#include "lab_handle.h"
#include "lab_mode.h"

/**
 * @brief Install native solver renderings and publish the retained TeX source.
 * @param mode Equation 1, differential equation 2, or integrator 4; other modes publish null without rendering.
 * @param data Scoped native response containing TeX, SVG and optional diagnostic/display variants.
 * @param expandable True permits equation digit expansion in mode 1; ignored in other modes.
 * @post Publishes the retained TeX string through lab_dom_return after updating the rendered card.
 */
void lab_evaluation_render(lab_mode_t mode, browser_jsref data, bool expandable);

/**
 * @brief Project expression notes and select the numerical value-card title.
 * @param data Scoped native response with value_note, root_value and differentiable fields.
 * @return False when differentiable trims and lower-cases to "no"; true otherwise, including an absent flag.
 */
bool lab_evaluation_notes(browser_jsref data);

/**
 * @brief Install native solver rendering after the caller verifies asynchronous ownership.
 * @param data Scoped native response supplying optional steps_wrapped_TeX.
 * @param source Scoped compact solver TeX string, also the fallback for the wrapped representation.
 * @param details Scoped plain-text solver details retained for display and copy operations.
 * @param svg Scoped native compact SVG string; no SVG is generated by this function.
 * @param token Scalar parent-request identity stored in the card dataset; not a scoped browser handle.
 */
void lab_evaluation_solver(browser_jsref data, browser_jsref source, browser_jsref details, browser_jsref svg, double token);

#endif

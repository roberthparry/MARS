    string_free(encoded_pattern);
    string_free(encoded_name);
    const char *args[] = {"--data-dir", data ? string_c_str(data) : ""};
    string_t *output = NULL;
    ok = ok && test_cfg_locales_run(directory, args, 2, 0, &output);

         string_append_utf8_exact(towns, string_c_str(encoded_town), string_byte_length(encoded_town)) == 0 &&
         string_append_utf8_exact(towns, "]", 1) == 0 &&
         test_cfg_locales_replace(string_c_str(data), "supplements.json", town_path, 3, string_c_str(towns));
    /* Town keys must use the installer's accent folding and whitespace collapse, not ASCII-only lowering. */

static const char *const test_cfg_locales_check_message =
    "Calendar locale seed matches Babel 2.17.0 / CLDR 46 and explicit supplements.\n";

static file_t *test_cfg_locales_file(const char *directory, const char *name)
{
    string_t *path = string_new();
    bool ok = path && string_append_utf8_exact(path, directory, strlen(directory)) == 0 &&
              string_append_utf8_exact(path, "/", 1) == 0 && string_append_utf8_exact(path, name, strlen(name)) == 0;
    file_t *file = ok ? file_new(path) : NULL;
    string_free(path);
    return file;
}

static bool test_cfg_locales_environment(void)
{
    return !setenv("MARS_ROOT", MARS_CONFIG_ROOT_DIR, 1);
}

static bool test_cfg_locales_run(const char *directory, const char *const *options, size_t count, int expected_status,
                                 string_t **output)
{
    const char *args[18] = {MARS_CONFIG_PROGRAM, "locales"};
    if (count > 15)
        return false;
    for (size_t i = 0; i < count; ++i)
        args[i + 2] = options[i];
    int status = -1;
    bool ran = lab_proc_run(args, directory, 60000, 4u * 1024u * 1024u, output, &status);
    bool ok = ran && status == expected_status;
    if (!ok)
        string_fprintf(stderr, "Locale generator: expected exit %d, got %d (collection %d): %S\n", expected_status,
                       status, ran, *output);
    return ok;
}

static bool test_cfg_locales_no_sql(const string_t *output)
{
    /* Diagnostics may be present in the merged stream, but no generated SQL may leak. */
    return output && string_find(output, "create table if not exists calendar_") < 0 &&
           string_find(output, "insert or replace into calendar_") < 0 && string_find(output, "-- Generated by ") < 0;
}

static bool test_cfg_locales_matches(file_t *file, const string_t *expected)
{
    string_t *actual = file ? file_read_all_text(file) : NULL;
    bool ok = actual && expected && string_view_equals_view(string_view_all(actual), string_view_all(expected));
    string_free(actual);
    return ok;
}

static bool test_cfg_locales_body_equal(const string_t *actual, const string_t *expected)
{
    /* Native provenance may differ; every byte from the first DDL statement must agree. */
    const char *first = "create table if not exists calendar_territory_locale (";
    string_offset_t a = actual ? string_find(actual, first) : -1;
    string_offset_t b = expected ? string_find(expected, first) : -1;
    bool ok = a >= 0 && b >= 0 &&
              string_view_equals_view(string_view(actual, (size_t)a, string_byte_length(actual) - (size_t)a),
                                      string_view(expected, (size_t)b, string_byte_length(expected) - (size_t)b));
    if (!ok)
        string_fprintf(stderr, "Native locale SQL body differs from the packaged reference\n");
    return ok;
}

static bool test_cfg_locales_query(sqlite_t *db, const char *sql, const char *expected)
{
    sqlite_stmt_t *stmt = sqlite_stmt_prepare(db, sql);
    bool ok = stmt && sqlite_stmt_step(stmt) == SQLITE_STEP_ROW;
    const char *raw = ok ? sqlite_stmt_column_text(stmt, 0) : NULL;
    string_t *value = raw ? string_new() : NULL;
    ok = ok && value && string_append_utf8_exact(value, raw, strlen(raw)) == 0 &&
         string_view_equals_literal(string_view_all(value), expected) && sqlite_stmt_step(stmt) == SQLITE_STEP_DONE;
    if (!ok)
        string_fprintf(stderr, "Generated locale query failed: %s; expected %s, got %S\n", sql, expected, value);
    string_free(value);
    sqlite_stmt_finalize(stmt);
    return ok;
}


static void test_cfg_locales_space(string_view_t view, string_pos_t *at)
{
    unsigned char ch;
    while (string_view_peek_ascii(view, *at, &ch) && (ch == ' ' || ch == '\n' || ch == '\r' || ch == '\t'))
        ++*at;
}

static bool test_cfg_locales_value_end(string_view_t view, string_pos_t *at, unsigned depth)
{
    /* Structural scanning of the checked-in JSON; generated invalid inputs go only to the engine. */
    if (depth > 32)
        return false;
    test_cfg_locales_space(view, at);
    unsigned char ch;
    if (!string_view_peek_ascii(view, *at, &ch))
        return false;
    if (ch == '"') {
        ++*at;
        uint32_t scalar;
        string_pos_t next;
        while (string_view_peek_rune_value(view, *at, &scalar, &next)) {
            *at = next;
            if (scalar == '"')
                return true;
            if (scalar == '\\') {
                if (!string_view_peek_rune_value(view, *at, &scalar, &next))
                    return false;
                *at = next;
            }
        }
        return false;
    }
    if (ch == '{' || ch == '[') {
        unsigned char close = ch == '{' ? '}' : ']';
        ++*at;
        while (*at < string_view_length(view)) {
            test_cfg_locales_space(view, at);
            if (!string_view_peek_ascii(view, *at, &ch))
                return false;
            if (ch == close) {
                ++*at;
                return true;
            }
            if (ch == ',' || ch == ':')
                ++*at;
            else if (!test_cfg_locales_value_end(view, at, depth + 1))
                return false;
        }
        return false;
    }
    string_pos_t start = *at;
    while (string_view_peek_ascii(view, *at, &ch) && ch != ',' && ch != '}' && ch != ']' && ch != ' ' && ch != '\n' &&
           ch != '\r' && ch != '\t')
        ++*at;
    return *at > start;
}

static bool test_cfg_locales_field(const string_t *text, string_pos_t at, const char *const *path, size_t depth,
                                   string_pos_t *start, string_pos_t *end)
{
    string_view_t view = string_view_all(text);
    unsigned char ch;
    test_cfg_locales_space(view, &at);
    if (!depth || depth > 8 || !string_view_peek_ascii(view, at, &ch) || ch != '{')
        return false;
    ++at;
    while (at < string_view_length(view)) {
        test_cfg_locales_space(view, &at);
        string_pos_t key_start = at;
        if (!string_view_peek_ascii(view, at, &ch) || ch != '"' || !test_cfg_locales_value_end(view, &at, 0))
            return false;
        string_t *encoded_key = string_substr(text, key_start, at - key_start);
        json_t *key = encoded_key ? json_from_text(encoded_key) : NULL;
        const string_t *name = key ? json_string_value(key) : NULL;
        bool match = name && string_view_equals_literal(string_view_all(name), path[0]);
        json_free(key);
        string_free(encoded_key);
        test_cfg_locales_space(view, &at);
        if (!string_view_peek_ascii(view, at, &ch) || ch != ':')
            return false;
        ++at;
        test_cfg_locales_space(view, &at);
        string_pos_t value_start = at;
        if (!test_cfg_locales_value_end(view, &at, 0))
            return false;
        if (match) {
            *start = value_start;
            *end = at;
            return depth == 1 || test_cfg_locales_field(text, value_start, path + 1, depth - 1, start, end);
        }
        test_cfg_locales_space(view, &at);
        if (!string_view_peek_ascii(view, at, &ch) || ch != ',')
            return false;
        ++at;
    }
    return false;
}

static bool test_cfg_locales_replace(const char *directory, const char *file_name, const char *const *path,
                                     size_t depth, const char *replacement)
{
    file_t *file = test_cfg_locales_file(directory, file_name);
    string_t *text = file ? file_read_all_text(file) : NULL;
    string_pos_t start = 0, end = 0;
    string_t *changed = string_new();
    bool ok = text && changed && test_cfg_locales_field(text, 0, path, depth, &start, &end) &&
              string_append_utf8_exact(changed, string_c_str(text), start) == 0 &&
              string_append_utf8_exact(changed, replacement, strlen(replacement)) == 0 &&
              string_append_utf8_exact(changed, string_c_str(text) + end, string_byte_length(text) - end) == 0 &&
              file_write_all_text(file, changed);
    string_free(changed);
    string_free(text);
    file_free(file);
    return ok;
}

static bool test_cfg_locales_fragment_paths(const char *directory, const char *data, file_t *destination,
                                            const string_t *sentinel)
{
    file_t *manifest_file = test_cfg_locales_file(data, "cldr46.json");
    string_t *text = manifest_file ? file_read_all_text(manifest_file) : NULL;
    json_t *manifest = text ? json_from_text(text) : NULL;
    const json_t *files = manifest ? test_cfg_locales_member(manifest, "locale_files") : NULL;
    const string_t *first = files ? json_string_value(json_array_get(files, 0)) : NULL;
    file_t *source = first ? test_cfg_locales_file(data, string_c_str(first)) : NULL;
    file_t *outside = test_cfg_locales_file(directory, "outside.json");
    bool ok = source && outside && file_copy(source, outside, true);
    const char *invalid[] = {"missing-fragment.json", "../outside.json", outside ? file_path(outside) : ""};
    const char *field[] = {"locale_files"};
    for (size_t i = 0; ok && i < sizeof invalid / sizeof *invalid; ++i) {
        json_t *list = json_new_array();
        string_t *name = string_new_with(invalid[i]);
        json_t *item = name ? json_new_string(name) : NULL;
        ok = list && item && json_array_append(list, item);
        for (size_t j = 1; ok && j < json_array_size(files); ++j)
            ok = json_array_append(list, json_array_get(files, j));
        /* A few ASCII filenames only; never re-serialise the large source tree. */
        string_t *replacement = ok ? json_to_string(list) : NULL;
        ok = ok && replacement && test_cfg_locales_replace(data, "cldr46.json", field, 1, string_c_str(replacement));
        string_t *output = NULL;
        const char *args[] = {"--data-dir", data, "--output", "preserved.sql"};
        ok = ok && test_cfg_locales_run(directory, args, 4, 1, &output) && test_cfg_locales_no_sql(output) &&
             test_cfg_locales_matches(destination, sentinel);
        string_free(output);
        string_free(replacement);
        json_free(item);
        string_free(name);
        json_free(list);
        ok = test_cfg_locales_copy_input(data, "cldr46.json") && ok;
    }
    file_free(outside);
    file_free(source);
    json_free(manifest);
    string_free(text);
    file_free(manifest_file);
    return ok;
}

